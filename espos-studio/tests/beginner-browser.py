"""Mock transport only: exercises real wizard UI and installation orchestration, not hardware."""
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome')
    page=browser.new_page(viewport={'width':1440,'height':1100})
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.add_init_script('''window.fileWrites=[];window.flashCount=0;window.romCount=0;window.actualChip='esp32s3';window.failInstall=false;window.failFlash=false;window.holdProbe=false;const bus=new EventTarget();let port;Object.defineProperty(navigator,'serial',{value:{addEventListener:bus.addEventListener.bind(bus),async requestPort(){port={open:async()=>{port.readable=new ReadableStream({start(c){window.emit=s=>c.enqueue(new TextEncoder().encode(s))}});port.writable=new WritableStream({write(){}})},close:async()=>{},getInfo:()=>({usbVendorId:0x10c4})};return port;}}});window.unplug=()=>{const e=new Event('disconnect');Object.defineProperty(e,'target',{value:port});bus.dispatchEvent(e)};''')
    def flash_module(route):
        route.fulfill(content_type='application/javascript',body='''export async function detectMicrocontroller(log,event){window.romCount++;event?.({stage:'rom',message:'Mock ROM'});if(window.holdProbe)await new Promise(r=>window.releaseProbe=r);return {board:window.actualChip,name:window.actualChip==='esp32s3'?'ESP32-S3':'ESP32-C3'}};export async function fetchFirmware(){return new Uint8Array(64)};export async function flashFirmware(image,opts){window.flashCount++;opts.onEvent?.({stage:'write',message:'Mock write'});if(window.failFlash)throw new Error('USB failed during write');opts.onDetected({board:'esp32s3',name:'ESP32-S3'});opts.onEvent?.({stage:'reset',message:'Mock done'});};''')
    def mpy_module(route):
        route.fulfill(content_type='application/javascript',body='''export const mpy={detach(){},async deviceInfo(){return {platform:'esp32',version:'MicroPython v1.29.0',freeMem:100000,fsFreeKb:1000,freqMhz:240}},async writeFile(path,content,onProgress){window.fileWrites.push({path,content});if(window.failInstall&&path==='/config.py')throw new Error('USB failed during install');onProgress?.(content.length,content.length)},async exec(code){if(code.includes('_c={}'))return JSON.stringify({version:'0.1.1-mvp',display:false,touch:false,lan:false});if(code.includes('ESPOS_USB_TEST:'))return 'ESPOS_USB_TEST:4';return ''},async softReset(){window.emit('MPY: soft reboot\\r\\nespOS 0.1.1-mvp on espOS\\r\\nespOS: ready / headless / USB\\r\\n')}};''')
    page.route('**/src/web/lib/flash.ts*',flash_module)
    page.route('**/src/web/lib/mpy.ts*',mpy_module)
    page.route('**/api/rpc/firmware/list*',lambda route:route.fulfill(json={'json':[{'board':'esp32s3','variant':'full','flashOffset':0,'flavour':f,'date':'20260824','version':'v1.29.0'+(' (SPIRAM_OCT)' if f!='standard' else ''),'filename':f+'.bin','url':'https://micropython.org/resources/firmware/'+f+'.bin'} for f in ['standard','SPIRAM_OCT']]}))
    page.goto('http://localhost:4200/')
    expect(page.get_by_role('button',name='Открыть простой старт',exact=True)).to_be_visible()
    assert page.evaluate('window.flashCount')==0
    page.screenshot(path='/tmp/simple-mode-choice.png')
    page.get_by_role('button',name='Открыть простой старт',exact=True).click()
    expect(page.get_by_role('button',name='Начать подключение',exact=True)).to_be_disabled()
    page.get_by_label('Подготовка платы',exact=True).check()
    page.get_by_role('button',name='Начать подключение',exact=True).click()
    page.get_by_role('button',name='Выбрать USB-порт платы',exact=True).click()
    probe=page.get_by_role('button',name='Проверить чип без записи',exact=True)
    page.evaluate("window.actualChip='esp32c3'")
    probe.click()
    expect(page.get_by_text('Подключён ESP32-C3, выбран ESP32-S3.',exact=False).first).to_be_visible()
    assert page.evaluate('window.flashCount')==0
    page.evaluate("window.actualChip='esp32s3';window.holdProbe=true")
    probe.click()
    expect(page.get_by_role('button',name='Сменить режим',exact=True)).to_be_disabled()
    page.wait_for_function('!!window.releaseProbe')
    page.evaluate('window.holdProbe=false;window.releaseProbe()')
    flash=page.get_by_role('button',name='Стереть и установить MicroPython',exact=True)
    expect(flash).to_be_disabled()
    page.get_by_label('Память для простого старта',exact=True).select_option('octal')
    expect(page.get_by_text('SPIRAM_OCT.bin',exact=False)).to_be_visible()
    expect(flash).to_be_disabled()
    page.get_by_label('Подтверждение стирания новичок',exact=True).check()
    page.evaluate('window.failFlash=true')
    flash.click()
    expect(page.get_by_text('Flash мог быть стёрт или записан частично.',exact=False)).to_be_visible()
    expect(flash).to_be_disabled()
    assert page.evaluate('window.flashCount')==1
    page.evaluate('window.failFlash=false')
    page.get_by_label('Подтверждение стирания новичок',exact=True).check()
    flash.click()
    expect(page.get_by_text('Запись завершена, но загрузка ещё не проверена.',exact=False)).to_be_visible()
    assert page.evaluate('window.fileWrites.length')==0
    page.get_by_role('button',name='Проверить установленный MicroPython',exact=True).click()
    install=page.get_by_role('button',name='Установить espOS без экрана',exact=True)
    expect(install).to_be_disabled()
    page.get_by_label('Подтверждение установки новичок',exact=True).check()
    page.evaluate('window.failInstall=true')
    install.click()
    expect(page.get_by_text('USB failed during install',exact=True).first).to_be_visible()
    expect(install).to_be_disabled()
    assert page.evaluate("window.fileWrites.filter(f=>f.path==='/config.py').length")==1
    page.evaluate('window.failInstall=false;window.fileWrites=[]')
    page.get_by_label('Подтверждение установки новичок',exact=True).check()
    install.click()
    verify=page.get_by_role('button',name='Перезапустить и проверить espOS',exact=True)
    expect(verify).to_be_enabled()
    writes=page.evaluate('window.fileWrites')
    assert writes[0]['path']=='/network_config.py' and 'ENABLED = False' in writes[0]['content']
    config=next(f['content'] for f in writes if f['path']=='/config.py')
    assert 'DISPLAY_ENABLED = False' in config and 'TOUCH_ENABLED = False' in config
    verify.click()
    expect(page.get_by_text('Свежий запуск espOS без экрана подтверждён',exact=False)).to_be_visible()
    page.get_by_role('button',name='Выполнить первый USB-тест',exact=True).click()
    expect(page.get_by_text('Плата посчитала 2 + 2 = 4.',exact=False)).to_be_visible()
    page.evaluate('window.unplug()')
    expect(page.get_by_role('button',name='Выполнить первый USB-тест',exact=True)).to_be_disabled()
    expect(page.get_by_text('После потери USB запуск нужно подтвердить заново.',exact=False)).to_be_visible()
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.screenshot(path='/tmp/simple-start-mobile.png')
    page.get_by_role('button',name='Сменить режим',exact=True).click()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.screenshot(path='/tmp/simple-mode-choice-mobile.png')
    assert not errors,errors
    print('PASS mode choice, S3 guard, busy lock, unknown memory, Octal selection, explicit erase/install, partial failures/no retry, headless/LAN off, fresh boot, USB demo, disconnect clears evidence, mobile overflow')
    browser.close()