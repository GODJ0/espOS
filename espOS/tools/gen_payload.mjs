// Generates packages/web/src/web/lib/espos-files.ts from firmware/ so espOS Studio
// can push the whole OS onto a device with one click.
// Usage: node tools/gen_payload.mjs
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

// fileURLToPath, not URL.pathname: on Windows the latter gives "/C:/..." and
// keeps non-ASCII folder names percent-encoded.
const root = dirname(fileURLToPath(import.meta.url));
const firmwareDir = join(root, "..", "firmware");
const out = join(root, "..", "..", "espos-studio", "packages", "web", "src", "web", "lib", "espos-files.ts");

function walk(dir, acc = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === "__pycache__" || entry.startsWith(".") || entry === "network_config.py") continue;
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (entry.endsWith(".py") || entry.endsWith(".md")) acc.push(p);
  }
  return acc;
}

const files = walk(firmwareDir)
  .filter((p) => p.endsWith(".py"))
  .map((p) => ({ path: "/" + relative(firmwareDir, p).split("\\").join("/"), content: readFileSync(p, "utf8") }))
  .sort((a, b) => a.path.localeCompare(b.path));

const body = files.map((f) => `  ${JSON.stringify(f.path)}: ${JSON.stringify(f.content)},`).join("\n");

const ts = `// AUTO-GENERATED by espOS/tools/gen_payload.mjs — do not edit by hand.
// Source of truth: espOS/firmware/. Regenerate after changing any firmware file.

export const ESPOS_VERSION = ${JSON.stringify(
  /FIRMWARE_VERSION\s*=\s*"([^"]+)"/.exec(readFileSync(join(firmwareDir, "config.py"), "utf8"))?.[1] ?? "0.0.0",
)};

export const esposFiles: Record<string, string> = {
${body}
};

export const esposFileList = Object.keys(esposFiles);
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, ts);
console.log(`wrote ${out} (${files.length} files, ${(ts.length / 1024).toFixed(1)} kB)`);
